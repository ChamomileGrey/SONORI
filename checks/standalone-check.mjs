import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';

const html = await fs.readFile(new URL('../release/SONORI.html', import.meta.url), 'utf8');
const scripts = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)];
assert.equal(scripts.length, 1, 'one self-contained script');
new vm.Script(scripts[0][1]);
const style = html.match(/<style>([\s\S]*?)<\/style>/)?.[1];
assert(style?.trim().startsWith(':root{'), 'font import removal must preserve the root CSS rule');
assert.match(style, /--ink:#282735/);
assert(!/@import/.test(style), 'standalone CSS must not load external fonts');
assert(!/<script[^>]+src=/.test(html), 'no external script');
assert(!/<link[^>]+rel="stylesheet"/.test(html), 'no external stylesheet');
assert(!/data-pages="1"/.test(html), 'pages-only links stay off the single file');
assert(!/<meta\b[^>]*name="sonori-sw"/.test(html), 'the single file does not register a service worker');
for (const match of html.matchAll(/<link\b([^>]*)>/g)) {
  const href = /href="([^"]*)"/.exec(match[1])?.[1] || '';
  const allowed = href.startsWith('data:') || href === 'https://chamomilegrey.github.io/SONORI/';
  assert.ok(allowed, `unexpected standalone link ${href}`);
}
assert(!/\bimport .* from /.test(scripts[0][1]), 'no file protocol module imports');
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(match => match[1]);
const staticHtml = html.replace(/<script>[\s\S]*?<\/script>/g, '');
const staticIds = [...staticHtml.matchAll(/\bid="([^"]+)"/g)].map(match => match[1]);
assert.equal(staticIds.length, new Set(staticIds).size, 'static IDs must be unique');
for (const [, ref] of staticHtml.matchAll(/\b(?:for|aria-controls|aria-labelledby)="([^"]+)"/g)) {
  for (const target of ref.split(' ')) assert(ids.includes(target), `reference ${target} exists`);
}
assert.match(html, /default-src 'none'/);
assert.match(html, /connect-src 'none'/);
assert.match(html, /id="playerBar"/);
assert.match(html, /id="libraryView"/);
assert.match(html, /data-genre-preset="cinematic"/);
assert.match(html, /data-genre-preset="modernrock"/);
assert.match(html, /data-layer="hum"/);
assert.match(html, /ko-fi\.com\/chamomilegrey/);
assert.match(html, /v1\.6\.0/);
assert.match(html, /id="conceptLine"/);
assert.match(html, /id="rerollBtn"/);
assert.match(html, /다른 느낌으로/);
assert.match(html, /data-scene="dawn-study"/);
assert.match(html, /data-scene="rain-cafe"/);
assert.match(html, /data-scene="bedtime"/);
assert.match(html, /id="ambienceRain"/);
assert.match(html, /id="creatorGuide"/);
assert.match(html, /Music: SONORI by ChamomileGrey/);
assert.match(scripts[0][1], /renderLoopWav/);
assert.match(scripts[0][1], /renderLongformWav/);
assert.match(scripts[0][1], /createAmbienceBuffers/);
assert.match(html, /data-genre-preset="pop"/);
assert.match(html, /data-genre-preset="rnb"/);
assert.match(html, /data-genre-preset="ambient"/);
assert.doesNotMatch(html, /id="genreChoices"/);
assert.doesNotMatch(html, /id="applyPresetBtn"/);
assert.doesNotMatch(html, /현재 데모에 이 프리셋 적용/);
assert.match(scripts[0][1], /vowelFormants/);
assert.match(scripts[0][1], /createConvolver/);
assert.match(scripts[0][1], /sonori\.studio\.v1/);
assert.match(scripts[0][1], /version:1/);
assert.match(html, /data-genre-preset="citypop"/);
assert.match(html, /data-genre-preset="trap"/);
assert.match(html, /data-genre-preset="house"/);
assert.match(html, /data-genre-preset="bossa"/);
assert.match(html, /data-genre-preset="reggaeton"/);
assert.match(html, /id="privacy"/);
assert.match(html, /분석 도구, 쿠키, 네트워크 호출은 없습니다/);
assert.match(html, /no analytics, cookies, or network calls/);
assert.match(scripts[0][1], /migrateStorage/);
assert.match(scripts[0][1], /applyPresetToSettings/);
assert.doesNotMatch(html, /fonts\.googleapis|youtube|googlevideo|cdn\./i);
console.log('PASS: standalone bundle syntax, root styles, offline assets, static IDs, labels and ARIA references.');
